local function __decodeBase64(encoded)
    local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local lookup = {}
    for index = 1, #alphabet do
        lookup[string.byte(alphabet, index)] = index - 1
    end

    local output = {}
    local buffer = 0
    local bits = 0
    for index = 1, #encoded do
        local value = lookup[string.byte(encoded, index)]
        if value ~= nil then
            buffer = buffer * 64 + value
            bits += 6
            if bits >= 8 then
                bits -= 8
                output[#output + 1] = string.char(math.floor(buffer / (2 ^ bits)) % 256)
                buffer %= 2 ^ bits
            end
        end
    end
    return table.concat(output)
end

local function __decompressLzss(packed)
    local bytes = {}
    local cursor = 1
    while cursor <= #packed do
        local flags = string.byte(packed, cursor)
        cursor += 1
        for bit = 0, 7 do
            if cursor > #packed then
                break
            end
            local isMatch = math.floor(flags / (2 ^ bit)) % 2 == 1
            if isMatch then
                local high, low, encodedLength = string.byte(packed, cursor, cursor + 2)
                cursor += 3
                local offset = high * 256 + low
                local length = encodedLength + 3
                if offset <= 0 or offset > #bytes then
                    error("[Note] Invalid compressed distribution payload", 0)
                end
                for _ = 1, length do
                    bytes[#bytes + 1] = bytes[#bytes - offset + 1]
                end
            else
                bytes[#bytes + 1] = string.byte(packed, cursor)
                cursor += 1
            end
        end
    end

    local chunks = {}
    local chunkSize = 1024
    for index = 1, #bytes, chunkSize do
        chunks[#chunks + 1] = string.char(table.unpack(
            bytes,
            index,
            math.min(index + chunkSize - 1, #bytes)
        ))
    end
    return table.concat(chunks)
end

